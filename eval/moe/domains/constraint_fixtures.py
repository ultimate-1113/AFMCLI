    return dict(variables=[dict(name=n,min=l,max=h) for n,(l,h) in zip(names,domains)],
                constraints=[dict(weights=list(w),relation=r,rhs=b) for w,r,b in constraints],
                objectives=[dict(weights=list(w),sense=s) for w,s in objectives])


